package com.lanrhyme.micyou.network

import io.ktor.network.sockets.openReadChannel
import io.ktor.network.sockets.openWriteChannel
import io.ktor.utils.io.readFully
import io.ktor.utils.io.readAvailable
import io.ktor.utils.io.writeFully
import kotlinx.coroutines.*
import org.junit.Assert.*
import org.junit.Test
import java.nio.file.Files
import java.security.KeyStore
import java.security.MessageDigest
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import javax.net.ssl.*

class PairingSecurityTest {
    private val pin = "11".repeat(32)
    private val token = "42".repeat(32)
    @Test fun parserRejectsMalformedCodesAndDoesNotPrintTheSecret() {
        val credentials = PairingCredentials.parse("ymic1:$pin:$token")
        assertEquals(32, credentials.tokenBytes().size)
        val bytes = credentials.tokenBytes(); bytes[0] = 0
        assertEquals(0x42.toByte(), credentials.tokenBytes()[0])
        assertFalse(credentials.toString().contains(token))
        for (value in listOf("", "ymic1:$pin", "ymic1:$pin:$token:extra", "ymic1:${"g".repeat(64)}:$token", "ymic2:$pin:$token")) {
            assertTrue(runCatching { PairingCredentials.parse(value) }.isFailure)
        }
    }

    private fun <T> withServer(block: (SSLContext, java.security.cert.Certificate) -> T): T {
        // A deliberately ephemeral TEST identity generated by the JDK, never a
        // production credential and never uploaded as an artifact.
        val dir = Files.createTempDirectory("ymic-jvm-tls-test-")
        val keystore = dir.resolve("test.p12")
        val log = dir.resolve("keytool.log")
        val tool = java.io.File(System.getProperty("java.home"), "bin/keytool" + if (System.getProperty("os.name", "").startsWith("Windows")) ".exe" else "")
        try {
            val process = ProcessBuilder(tool.absolutePath, "-genkeypair", "-alias", "test", "-storetype", "PKCS12",
                "-keystore", keystore.toString(), "-storepass", "test-only-password", "-keyalg", "EC", "-groupname", "secp256r1",
                "-dname", "CN=localhost", "-ext", "SAN=dns:localhost", "-validity", "2", "-noprompt")
                .redirectErrorStream(true).redirectOutput(log.toFile()).start()
            if (!process.waitFor(20, TimeUnit.SECONDS)) { process.destroyForcibly(); fail("Test certificate generation timed out") }
            assertEquals("Test certificate generation failed", 0, process.exitValue())
            val store = KeyStore.getInstance("PKCS12").apply { Files.newInputStream(keystore).use { load(it, "test-only-password".toCharArray()) } }
            val keys = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm()).apply { init(store, "test-only-password".toCharArray()) }
            val context = SSLContext.getInstance("TLS").apply { init(keys.keyManagers, null, null) }
            return block(context, store.getCertificate("test"))
        } finally {
            Files.deleteIfExists(keystore); Files.deleteIfExists(log); Files.deleteIfExists(dir)
        }
    }

    @Test fun pinnedTlsCarriesTheCredentialAndAudio() = withServer { context, certificate -> runBlocking {
        val actualPin = MessageDigest.getInstance("SHA-256").digest(certificate.encoded).joinToString("") { "%02x".format(it) }
        val credentials = PairingCredentials.parse("ymic1:$actualPin:$token")
        val server = context.serverSocketFactory.createServerSocket(0, 1, java.net.InetAddress.getByName("127.0.0.1")) as SSLServerSocket
        val executor = Executors.newSingleThreadExecutor()
        val received = executor.submit<ByteArray> {
            (server.accept() as SSLSocket).use { socket ->
                socket.soTimeout = 3000; socket.startHandshake()
                val auth = socket.inputStream.readNBytes(40)
                assertArrayEquals(PairingCredentials.AUTH_MAGIC + credentials.tokenBytes(), auth)
                socket.outputStream.write(PairingCredentials.AUTH_OK); socket.outputStream.flush()
                val audio = socket.inputStream.readNBytes(5)
                socket.outputStream.write("end".toByteArray()); socket.outputStream.flush()
                audio
            }
        }
        val client = PinnedTlsSocket(credentials, coroutineContext)
        try {
            withTimeout(5000) {
                client.connect("127.0.0.1", server.localPort)
                val input = client.openReadChannel(); val output = client.openWriteChannel(autoFlush = true)
                output.writeFully(PairingCredentials.AUTH_MAGIC); output.writeFully(credentials.tokenBytes()); output.flush()
                val acknowledgement = ByteArray(4); input.readFully(acknowledgement, 0, 4)
                assertArrayEquals(PairingCredentials.AUTH_OK, acknowledgement)
                output.writeFully("audio".toByteArray()); output.flush()
                val tail = ByteArray(3); input.readFully(tail, 0, tail.size)
                assertArrayEquals("end".toByteArray(), tail)
                assertEquals(-1, input.readAvailable(ByteArray(1), 0, 1))
            }
            assertArrayEquals("audio".toByteArray(), received.get(5, TimeUnit.SECONDS))
        } finally { client.close(); server.close(); executor.shutdownNow() }
    } }

    @Test fun aWrongPinFailsBeforeAnyApplicationBytesAreSent() = withServer { context, _ -> runBlocking {
        val server = context.serverSocketFactory.createServerSocket(0, 1, java.net.InetAddress.getByName("127.0.0.1")) as SSLServerSocket
        val executor = Executors.newSingleThreadExecutor()
        val received = executor.submit<Int> {
            (server.accept() as SSLSocket).use { socket ->
                socket.soTimeout = 3000
                try { socket.startHandshake(); socket.inputStream.read() } catch (_: java.io.IOException) { -1 }
            }
        }
        val client = PinnedTlsSocket(PairingCredentials.parse("ymic1:$pin:$token"), coroutineContext)
        try {
            assertTrue(runCatching { withTimeout(5000) { client.connect("127.0.0.1", server.localPort) } }.isFailure)
            assertEquals(-1, received.get(5, TimeUnit.SECONDS))
            assertTrue(client.socketContext.isCancelled)
        } finally { client.close(); server.close(); executor.shutdownNow() }
    } }

    @Test fun closeInterruptsABlockedTlsHandshake() = runBlocking {
        val server = java.net.ServerSocket(0, 1, java.net.InetAddress.getByName("127.0.0.1"))
        val executor = Executors.newSingleThreadExecutor()
        val accepted = executor.submit<java.net.Socket> { server.accept() }
        val client = PinnedTlsSocket(PairingCredentials.parse("ymic1:$pin:$token"), coroutineContext)
        val connecting = async { runCatching { client.connect("127.0.0.1", server.localPort) } }
        try {
            val peer = withContext(Dispatchers.IO) { accepted.get(3, TimeUnit.SECONDS) }
            peer.use {
                peer.soTimeout = 3000
                // Wait for the TLS ClientHello so close interrupts an actual
                // handshake rather than racing before it has started.
                assertEquals(22, withContext(Dispatchers.IO) { peer.inputStream.read() })
                client.close()
                assertTrue(withTimeout(3000) { connecting.await() }.isFailure)
            }
        } finally { client.close(); server.close(); executor.shutdownNow() }
    }
}
